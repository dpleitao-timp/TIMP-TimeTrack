function initialLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (LANGS.some((l) => l.code === stored)) return stored
  } catch {
    /* ignora */
  }
  const nav = (navigator.language || '').slice(0, 2).toLowerCase()
  return LANGS.some((l) => l.code === nav) ? nav : DEFAULT_LANG
}

const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(initialLang)
  const locale = LANGS.find((l) => l.code === lang).locale

  const setLang = useCallback((code) => {
    try {
      localStorage.setItem(STORAGE_KEY, code)
    } catch {
      /* ignora */
    }
    setLangState(code)
  }, [])

  const t = useCallback(
    (key, vars = {}) => {
      const text = dict[lang]?.[key] ?? dict.pt[key] ?? key
      return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
    },
    [lang],
  )

  useEffect(() => {
    document.documentElement.lang = lang
    document.title = t('app.title')
  }, [lang, t])

  const value = useMemo(() => ({ t, lang, setLang, locale }), [t, lang, setLang, locale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useT = () => useContext(I18nContext)

// Seletor PT / FR / EN / DE (sempre visível: quem pica pode precisar de mudar de língua).
export function LanguageSwitch() {
  const { lang, setLang, t } = useT()
  return (
    <div className="lang-switch" role="group" aria-label={t('lang.label')}>
      {LANGS.map((l) => (
        <button key={l.code} type="button" className={l.code === lang ? 'on' : ''} title={l.label} aria-pressed={l.code === lang} onClick={() => setLang(l.code)}>
          {l.code.toUpperCase()}
        </button>
      ))}
    </div>
  )
}
